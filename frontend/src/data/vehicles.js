/** Builds the derived fields so each listing below only states what is
 *  distinctive about that vehicle. */
function defineVehicle(spec) {
  const slug = `${spec.year}-${spec.make}-${spec.model}-${spec.trim}`
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '')

  const imageCount = spec.imageCount ?? 5

  return {
    ...spec,
    slug,
    title: `${spec.year} ${spec.make} ${spec.model} ${spec.trim}`,
    images: Array.from({ length: imageCount }, (_, index) =>
      vehicleImage(slug, index + 1),
    ),
    // The price a buyer actually pays attention to. `salePrice` wins when the
    // vehicle is discounted, which is why the UI never reads `price` directly.
    effectivePrice: spec.salePrice ?? spec.price,
  }
}

